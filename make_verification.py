#!/usr/bin/env python3
"""ICU AND YOU — build verification.js from verification.json.

The JSON is the record you edit. This turns it into the runtime the pages load,
the same arrangement as glossary.py -> glossary.js.

A page is only advertised as verified when EVERY numeric claim on it is listed
in verification.json. audit.py enforces that, and also reports what is due for
review, so nothing ages quietly.

    python3 make_verification.py
"""
import json, re, sys
from datetime import date
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE / "verification.json"
OUT = HERE / "verification.js"

MONTHS = ("January February March April May June July August September "
          "October November December").split()


def human(iso):
    """2026-10-23 -> 23 October 2026 ; 2027-10 -> October 2027"""
    p = iso.split("-")
    if len(p) == 3:
        return f"{int(p[2])} {MONTHS[int(p[1]) - 1]} {p[0]}"
    return f"{MONTHS[int(p[1]) - 1]} {p[0]}"


def due(checked, interval):
    """Review date from the date checked and the interval. 'never' means never."""
    if interval == "never":
        return None
    m = re.fullmatch(r"(\d+)m", interval)
    if not m:
        raise SystemExit(f"unknown interval {interval!r} — use 'never' or e.g. '12m'")
    y, mo, _ = (int(x) for x in checked.split("-"))
    mo += int(m.group(1))
    y += (mo - 1) // 12
    mo = (mo - 1) % 12 + 1
    return f"{y}-{mo:02d}"


def main():
    data = json.loads(SRC.read_text(encoding="utf-8"))
    claims, pages = data["claims"], data["pages"]

    out = {}
    for cid, c in claims.items():
        d = due(c["checked"], c["interval"])
        out[cid] = {
            "c": c["claim"],
            "s": c["source"],
            "u": c.get("url", ""),
            "d": human(c["checked"]),
            "r": human(d) if d else None,
            "v": c["verdict"],
            "n": c.get("note", ""),
        }

    pg = {}
    for f, p in pages.items():
        ids = [i for i, c in claims.items() if c["page"] == f]
        if not ids:
            raise SystemExit(f"{f} is listed as a verified page but has no claims")
        latest = max(claims[i]["checked"] for i in ids)
        rs = [due(claims[i]["checked"], claims[i]["interval"]) for i in ids]
        rs = [r for r in rs if r]
        pg[f] = {
            "d": human(latest),
            "r": human(min(rs)) if rs else None,
            "n": len(ids),
        }

    js = OUT_TEMPLATE.replace("/*CLAIMS*/", json.dumps(out, ensure_ascii=False)) \
                     .replace("/*PAGES*/", json.dumps(pg, ensure_ascii=False))
    OUT.write_text(js, encoding="utf-8")

    # what is due, soonest first — the line the Friday audit repeats
    today = date.today().strftime("%Y-%m")
    rows = []
    for cid, c in claims.items():
        d = due(c["checked"], c["interval"])
        if d:
            rows.append((d, cid, c["page"]))
    rows.sort()
    overdue = [r for r in rows if r[0] <= today]
    print(f"verification.js written — {len(claims)} claims across {len(pages)} page(s)")
    if overdue:
        print(f"  {len(overdue)} DUE FOR REVIEW: " + ", ".join(r[1] for r in overdue))
    elif rows:
        print(f"  next review {human(rows[0][0])} ({rows[0][1]})")


