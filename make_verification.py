#!/usr/bin/env python3
"""ICU AND YOU — build verification.js from verification.json.

The JSON is the record you edit. This turns it into the runtime the pages load,
the same arrangement as glossary.py -> glossary.js.

A page is only advertised as verified when EVERY numeric claim on it is listed
in verification.json. audit.py enforces that, and also reports what is due for
review, so nothing ages quietly.

    python3 make_verification.py
"""
import json, re, sys
from datetime import date
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE / "verification.json"
OUT = HERE / "verification.js"

MONTHS = ("January February March April May June July August September "
          "October November December").split()


def human(iso):
    """2026-10-23 -> 23 October 2026 ; 2027-10 -> October 2027"""
    p = iso.split("-")
    if len(p) == 3:
        return f"{int(p[2])} {MONTHS[int(p[1]) - 1]} {p[0]}"
    return f"{MONTHS[int(p[1]) - 1]} {p[0]}"


def due(checked, interval):
    """Review date from the date checked and the interval. 'never' means never."""
    if interval == "never":
        return None
    m = re.fullmatch(r"(\d+)m", interval)
    if not m:
        raise SystemExit(f"unknown interval {interval!r} — use 'never' or e.g. '12m'")
    y, mo, _ = (int(x) for x in checked.split("-"))
    mo += int(m.group(1))
    y += (mo - 1) // 12
    mo = (mo - 1) % 12 + 1
    return f"{y}-{mo:02d}"


def main():
    data = json.loads(SRC.read_text(encoding="utf-8"))
    claims, pages = data["claims"], data["pages"]

    out = {}
    for cid, c in claims.items():
        d = due(c["checked"], c["interval"])
        out[cid] = {
            "c": c["claim"],
            "s": c["source"],
            "u": c.get("url", ""),
            "d": human(c["checked"]),
            "r": human(d) if d else None,
            "v": c["verdict"],
            "n": c.get("note", ""),
        }

    pg = {}
    for f, p in pages.items():
        ids = [i for i, c in claims.items() if c["page"] == f]
        if not ids:
            raise SystemExit(f"{f} is listed as a verified page but has no claims")
        latest = max(claims[i]["checked"] for i in ids)
        rs = [due(claims[i]["checked"], claims[i]["interval"]) for i in ids]
        rs = [r for r in rs if r]
        # Flagged claims are the ones where the primary source was not read.
        # The band counts them separately, because "all N against primary
        # sources" would otherwise be a sentence the record itself contradicts.
        pg[f] = {
            "d": human(latest),
            "r": human(min(rs)) if rs else None,
            "n": len(ids),
            "f": sum(1 for i in ids if claims[i]["verdict"] == "flagged"),
        }

    js = OUT_TEMPLATE.replace("/*CLAIMS*/", json.dumps(out, ensure_ascii=False)) \
                     .replace("/*PAGES*/", json.dumps(pg, ensure_ascii=False))
    OUT.write_text(js, encoding="utf-8")

    # what is due, soonest first — the line the Friday audit repeats
    today = date.today().strftime("%Y-%m")
    rows = []
    for cid, c in claims.items():
        d = due(c["checked"], c["interval"])
        if d:
            rows.append((d, cid, c["page"]))
    rows.sort()
    overdue = [r for r in rows if r[0] <= today]
    print(f"verification.js written — {len(claims)} claims across {len(pages)} page(s)")
    if overdue:
        print(f"  {len(overdue)} DUE FOR REVIEW: " + ", ".join(r[1] for r in overdue))
    elif rows:
        print(f"  next review {human(rows[0][0])} ({rows[0][1]})")


OUT_TEMPLATE = r'''/* ICU AND YOU — verification markers. GENERATED by make_verification.py.
   Edit verification.json, not this file.

   <sup class="vf" data-v="id"></sup> after a number becomes click-to-open,
   and a page listed in P gets a band saying every number on it was checked.
   Deliberately unlike the glossary: a raised mark AFTER a number, not a
   dotted underline UNDER a word, so the two systems never read as one. */
(function(){
  var V = /*CLAIMS*/;
  var P = /*PAGES*/;

  var css = document.createElement("style");
  css.textContent =
    "sup.vf{font:600 10px 'Helvetica Neue',Arial,sans-serif;color:#2E6473;" +
      "cursor:pointer;margin-left:2px;vertical-align:super;line-height:0;" +
      "border:0;background:none;padding:0 1px}" +
    "sup.vf::after{content:'\\2713'}" +
    "sup.vf:hover,sup.vf.open{color:#A8442A}" +
    /* A mind map keeps its claims inside its SVG, where a <sup> cannot
       go and ::after is never rendered. The tick is therefore a real
       <text> carrying the check character; only colour and cursor
       come from here. Document CSS does style inline SVG. */
    "text.vf,tspan.vf{fill:#2E6473;cursor:pointer;" +
      "font:600 11px 'Helvetica Neue',Arial,sans-serif}" +
    "text.vf:hover,text.vf.open,tspan.vf:hover,tspan.vf.open{fill:#A8442A}" +
    ".vf-card{position:absolute;z-index:60;max-width:340px;background:#FFFFFF;" +
      "border:1px solid #D8D4CA;border-radius:10px;padding:15px 17px;" +
      "box-shadow:0 6px 26px rgba(27,42,51,.16);" +
      "font:400 14.5px/1.5 'Iowan Old Style',Palatino,Georgia,serif;color:#25303A}" +
    ".vf-card b{display:block;font:600 11px 'Helvetica Neue',Arial,sans-serif;" +
      "letter-spacing:.14em;text-transform:uppercase;margin:0 0 7px;color:#2E6473}" +
    ".vf-card .cl{display:block;font-style:italic;margin:0 0 9px;color:#1B2A33}" +
    ".vf-card p{margin:0 0 8px}" +
    ".vf-card p:last-child{margin:0}" +
    ".vf-card .mt{font:400 13px 'Helvetica Neue',Arial,sans-serif;color:#6E6B63}" +
    ".vf-card a{color:#2E6473}" +
    ".vf-band{margin:26px 0 0;padding:13px 17px;background:#EDF2F3;" +
      "border-left:4px solid #2E6473;border-radius:0 7px 7px 0;" +
      "font:400 14px/1.55 'Helvetica Neue',Arial,sans-serif;color:#44525A}" +
    ".vf-band b{color:#2E6473}" +
    "@media print{sup.vf,text.vf,tspan.vf{display:none}.vf-card{display:none}}";
  document.head.appendChild(css);

  var card = null, current = null;
  function close(){
    if(card){ card.remove(); card = null; }
    if(current){ current.classList.remove("open"); current = null; }
  }
  function open(el){
    var v = V[el.getAttribute("data-v")];
    if(!v) return false;
    close();
    var verdict = {confirmed:"Checked and confirmed", corrected:"Checked and corrected",
                   contested:"Checked — genuinely contested",
                   flagged:"Checked — one open question"}[v.v] || "Checked";
    card = document.createElement("div");
    card.innerHTML = "<b>" + verdict + "</b>"
      + "<span class='cl'>" + v.c + "</span>"
      + "<p>Against " + (v.u ? "<a href='" + v.u + "'>" + v.s + "</a>" : v.s)
      + ", on " + v.d + ".</p>"
      + (v.r ? "<p class='mt'>Due for review " + v.r + ".</p>"
             : "<p class='mt'>Settled — no review needed.</p>")
      + (v.n ? "<p class='mt'>" + v.n + "</p>" : "");
    card.className = "vf-card";
    document.body.appendChild(card);
    var r = el.getBoundingClientRect(), w = card.offsetWidth;
    var top = r.bottom + window.scrollY + 8, left = r.left + window.scrollX;
    if(left + w > window.innerWidth - 14) left = window.innerWidth - w - 14;
    if(left < 10) left = 10;
    if(r.bottom + card.offsetHeight + 20 > window.innerHeight)
      top = r.top + window.scrollY - card.offsetHeight - 8;
    /* A tall card flipped upward can finish above the top of the window, which
       hides the claim and the verdict — the two lines the reader opened it for.
       Clamp it: a card taller than the window then runs off the bottom, where
       the page can at least be scrolled to reach it. */
    if(top < window.scrollY + 10) top = window.scrollY + 10;
    card.style.top = top + "px"; card.style.left = left + "px";
    el.classList.add("open"); current = el;
    return true;
  }

  document.addEventListener("click", function(ev){
    var el = ev.target.closest ? ev.target.closest("sup.vf, text.vf, tspan.vf") : null;
    if(el){ ev.preventDefault(); if(current === el) close(); else open(el); return; }
    if(card && !ev.target.closest(".vf-card")) close();
  });
  document.addEventListener("keydown", function(e){ if(e.key === "Escape") close(); });
  window.addEventListener("resize", close);

  /* the page-level band — only for pages where every number has been done */
  var here = location.pathname.split("/").pop() || "index.html";
  var p = P[here];
  if(p){
    /* The mnemonic series is built on .wrap > .card and has no .pad at all,
       so until November 2026 this quietly found no host and no band ever
       appeared on those pages — silently, which is the worst way to fail.
       Fall back to .card, and place the band before a footer when the host
       contains one rather than after it. */
    var host = document.querySelector(".pad:last-of-type")
            || document.querySelector(".pad")
            || document.querySelector(".card");
    if(host){
      var b = document.createElement("div");
      b.className = "vf-band";
      b.innerHTML = "<b>Every number on this page has been checked.</b> " +
        (p.f ? "All " + p.n + " against their sources on " + p.d + " \u2014 " +
               (p.n - p.f) + " against primary sources, and " + p.f +
               " flagged, where the primary could not be read."
             : "All " + p.n + " against primary sources, on " + p.d + ".") +
        (p.r ? " Next review " + p.r + "." : "") +
        " The ticks show what was checked and against what.";
      var foot = host.querySelector(":scope > footer");
      if(foot){ host.insertBefore(b, foot); } else { host.appendChild(b); }
    }
  }
})();
'''

if __name__ == "__main__":
    main()
